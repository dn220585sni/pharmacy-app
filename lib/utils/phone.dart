/// Звести введений номер до 9 цифр національної частини (без коду країни).
///
/// Поля вводу телефону в касі мають статичний префікс «+380», але касири
/// звично починають з нуля — «050 123 45 67». Виходило `+3800501234567` із
/// зайвим нулем: підказка в полі сама пропонувала формат із нулем, а код
/// просто клеїв введене до префікса (беклог Юлії, «Рука допомоги»).
///
/// Приймаємо всі звичні варіанти: `50…`, `050…`, `380…`, `+380…`, з пробілами
/// й дужками. Повертає до 9 цифр; коротший ввід віддається як є, щоб виклик
/// міг сам вирішити, чи номер уже повний.
String nationalDigits(String raw) {
  var d = raw.replaceAll(RegExp(r'\D'), '');
  if (d.startsWith('380')) d = d.substring(3);
  if (d.startsWith('0')) d = d.substring(1);
  return d.length > 9 ? d.substring(0, 9) : d;
}
