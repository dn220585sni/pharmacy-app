import 'package:flutter_test/flutter_test.dart';
import 'package:pharmacy_app/utils/phone.dart';

/// Поля телефону в касі мають статичний префікс «+380», тож у код має
/// потрапляти рівно національна частина. Зайвий нуль на початку давав
/// `+3800501234567` — саме це Юлія завела в беклог по «Руці допомоги».
void main() {
  group('nationalDigits', () {
    test('касир набрав із нулем, як пропонувала стара підказка', () {
      expect(nationalDigits('050 123 45 67'), '501234567');
    });

    test('касир набрав без нуля — нічого не змінюємо', () {
      expect(nationalDigits('50 123 45 67'), '501234567');
    });

    test('вставлений повний номер із кодом країни', () {
      expect(nationalDigits('+380 50 123 45 67'), '501234567');
      expect(nationalDigits('380501234567'), '501234567');
      expect(nationalDigits('+38 (050) 123-45-67'), '501234567');
    });

    test('оператор, що починається з 9 — нуль не чіпаємо зайвий раз', () {
      expect(nationalDigits('097 000 11 22'), '970001122');
      expect(nationalDigits('97 000 11 22'), '970001122');
    });

    test('зайві цифри в кінці відрізаються до 9', () {
      expect(nationalDigits('0501234567890'), '501234567');
    });

    test('неповний ввід віддається як є — щоб виклик знав, що ще рано', () {
      expect(nationalDigits('50 123'), '50123');
      expect(nationalDigits(''), '');
      expect(nationalDigits('   '), '');
    });

    test('літери й розділові знаки ігноруються', () {
      expect(nationalDigits('тел. 050-123-45-67'), '501234567');
    });
  });
}
